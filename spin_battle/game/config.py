# Лёгкий разгоняется/манёврит легче; влияет на отзывчивость рыскания.
def agility(weight: float) -> float:
    """Манёвренность: лёгкий волчок вёрткий, тяжёлый инертный (0.4..1.4)."""
    t = (weight - WEIGHT_MIN) / (WEIGHT_MAX - WEIGHT_MIN)
    return 1.4 - t  # 1.4 у лёгкого -> 0.4 у тяжёлого


